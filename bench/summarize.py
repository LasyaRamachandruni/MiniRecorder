#!/usr/bin/env python3
"""Builds bench/results/RESULTS.md from the JSON files written by
run_micro.sh and run_e2e.sh. Only formats numbers; computes nothing that is
not in the JSON except ratios and per-second rates."""

import json
import sys
from pathlib import Path

RES = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent / "results"
RECORD_HEADER = 24  # bytes per record in a chunk body


def load(name):
    return json.loads((RES / name).read_text())


def micro_rows(name):
    data = load(name)
    rows = {}
    for b in data["benchmarks"]:
        if b.get("aggregate_name") == "median":
            rows[b["run_name"]] = b
    return rows


def fmt(x, digits=1):
    return f"{x:,.{digits}f}"


out = []
w = out.append

w("# Benchmark results\n")
w("Generated by `bench/summarize.py` from the JSON files in this directory.")
w("All sensor data is SYNTHETIC (built-in simulator). Hardware and toolchain:")
w("")
w("```")
w((RES / "machine.txt").read_text().split("\nlscpu:")[0].rstrip())
w("```\n")

# ---------------------------------------------------------------- micro: ring
ring = micro_rows("micro_ring.json")
w("## Ring buffer (Google Benchmark, median of 5)\n")
w("Command: `bench/run_micro.sh` (`bench_ring --benchmark_repetitions=5 --benchmark_min_time=0.2s`).")
w("One producer thread and one consumer thread, 64-byte messages, capacity 1024.\n")
w("| Queue | Throughput (M msg/s) | MB/s |")
w("|---|---:|---:|")
for key, label in [
    ("BM_Throughput_SpscQueue/real_time", "SpscQueue (lock-free SPSC)"),
    ("BM_Throughput_MutexQueue/real_time", "std::mutex + std::queue (spin try_push/try_pop)"),
    ("BM_Throughput_CondvarQueue/real_time", "std::mutex + std::queue + condition variables"),
    ("BM_Throughput_RecordRing/48/real_time", "RecordRing, 48 B payload (IMU)"),
]:
    b = ring[key]
    w(f"| {label} | {fmt(b['items_per_second'] / 1e6, 2)} | {fmt(b['bytes_per_second'] / 1e6)} |")
cam = ring["BM_Throughput_RecordRing/307216/real_time"]
w(f"| RecordRing, 307,216 B payload (640x480 frame) | {fmt(cam['items_per_second'] / 1e3, 1)} k frames/s | {fmt(cam['bytes_per_second'] / 1e6, 0)} |")
spsc = ring["BM_Throughput_SpscQueue/real_time"]["items_per_second"]
mtx = ring["BM_Throughput_MutexQueue/real_time"]["items_per_second"]
w(f"\nSpscQueue vs mutex queue: {spsc / mtx:.1f}x throughput.\n")
w("Round trip (ping-pong through two queues, one message in flight):\n")
w("| Queue | RTT p50 (ns) | RTT p99 (ns) |")
w("|---|---:|---:|")
for key, label in [("BM_PingPong_SpscQueue/real_time", "SpscQueue"),
                   ("BM_PingPong_MutexQueue/real_time", "std::mutex + std::queue")]:
    b = ring[key]
    w(f"| {label} | {fmt(b['rtt_p50_ns'], 0)} | {fmt(b['rtt_p99_ns'], 0)} |")
w("")

# ---------------------------------------------------------------- micro: codec
codec = micro_rows("micro_codec.json")
w("## CRC32C and chunk codec (Google Benchmark, median of 5)\n")
w("| Benchmark | Throughput |")
w("|---|---:|")
for key, label in [("BM_Crc32c_Portable/1048576", "CRC32C slice-by-8, 1 MiB"),
                   ("BM_Crc32c_Hardware/1048576", "CRC32C SSE4.2, 1 MiB")]:
    w(f"| {label} | {fmt(codec[key]['bytes_per_second'] / 1e9, 2)} GB/s |")
for key, label in [("BM_DecodeChunk/1", "chunk verify + decompress, IMU (zstd 3)"),
                   ("BM_DecodeChunk/4", "chunk verify + decompress, camera (zstd 3)")]:
    w(f"| {label} | {fmt(codec[key]['bytes_per_second'] / 1e6, 0)} MB/s |")
w("")
w("Encoding one ~1 MiB chunk of each stream type (ratio = uncompressed record bytes / chunk bytes):\n")
w("| Stream | zstd 1 ratio | zstd 1 MB/s | zstd 3 ratio | zstd 3 MB/s | zstd 9 ratio | zstd 9 MB/s |")
w("|---|---:|---:|---:|---:|---:|---:|")
for kind, label in [(1, "imu"), (2, "gps"), (3, "wheel_can"), (4, "camera 640x480")]:
    cells = []
    for level in (1, 3, 9):
        b = codec[f"BM_EncodeChunk/{kind}/{level}"]
        cells += [fmt(b["ratio"], 2), fmt(b["bytes_per_second"] / 1e6, 0)]
    w(f"| {label} | " + " | ".join(cells) + " |")
w("")

# ---------------------------------------------------------------- e2e throughput
w("## End-to-end recorder throughput\n")
w("Command: `mr_record --unpaced --policy all=block --duration 8 --zstd-level N --fsync interval:100` "
  "(lossless: producers block instead of dropping). Rates are over wall time including the final drain.\n")
w("| Scenario | zstd | Records/s | Input MB/s | Disk MB/s | Ratio | Compress CPU s | Drops |")
w("|---|---:|---:|---:|---:|---:|---:|---:|")
for prefix, label in [("throughput_zstd", "full set (camera 640x480)"),
                      ("throughput_small_zstd", "small records only (camera off)")]:
    for level in (1, 3, 9):
        d = load(f"{prefix}{level}.json")
        e = d["elapsed_s"]
        drops = sum(s["ring_dropped_newest"] + s["ring_evicted_oldest"] for s in d["streams"])
        w(f"| {label} | {level} | {fmt(d['records_written'] / e, 0)} | {fmt(d['record_bytes'] / 1e6 / e)} | "
          f"{fmt(d['file_bytes'] / 1e6 / e)} | {d['record_bytes'] / d['file_bytes']:.2f} | "
          f"{fmt(d['compress_cpu_s'], 2)} | {drops} |")
w("")
w("Compression ratio per stream in the full-set runs (uncompressed record bytes incl. 24 B record "
  "headers / bytes on disk):\n")
w("| Stream | zstd 1 | zstd 3 | zstd 9 |")
w("|---|---:|---:|---:|")
names = [s["name"] for s in load("throughput_zstd1.json")["streams"] if s["name"] != "_events"]
for name in names:
    cells = []
    for level in (1, 3, 9):
        s = next(x for x in load(f"throughput_zstd{level}.json")["streams"] if x["name"] == name)
        raw = s["payload_bytes"] + RECORD_HEADER * s["records"]
        cells.append(f"{raw / s['stored_bytes']:.2f}" if s["stored_bytes"] else "n/a")
    w(f"| {name} | " + " | ".join(cells) + " |")
w("")

# ---------------------------------------------------------------- durability
w("## Enqueue-to-durable latency per fsync policy\n")
w("Command: `mr_record --duration 10 --fsync P --chunk-age-ms A --track-latency` at nominal rates "
  "(IMU 200 Hz, GPS 10 Hz, wheel 100 Hz, camera 640x480 @ 30 Hz, about 9.2 MB/s). Latency is per "
  "record from the producer's push to the return of write(2) (\"written\") and of the covering "
  "fdatasync (\"durable\").\n")
w("| fsync | chunk age | written p50 ms | written p99 ms | durable p50 ms | durable p99 ms | fsyncs | fsync time s |")
w("|---|---:|---:|---:|---:|---:|---:|---:|")
for age in (500, 50):
    for policy, label in [("chunk", "every chunk"), ("interval_100", "every 100 ms"), ("close", "at close")]:
        d = load(f"durability_{policy}_age{age}.json")
        wl, dl = d["write_latency"], d["durable_latency"]
        w(f"| {label} | {age} ms | {fmt(wl['p50_ms'])} | {fmt(wl['p99_ms'])} | {fmt(dl['p50_ms'])} | "
          f"{fmt(dl['p99_ms'])} | {d['fsync_count']} | {d['fsync_s']:.3f} |")
w("")

# ---------------------------------------------------------------- overload
w("## Overload: drops per overflow policy\n")
w("Command: `mr_record --rate-scale 30 --policy all=P --zstd-level 9 --duration 5` "
  "(sensors paced at 30x nominal, about 275 MB/s offered, into zstd level 9).\n")
w("| Policy | Stream | Produced | Persisted | Dropped newest | Evicted oldest | Producer blocked s |")
w("|---|---|---:|---:|---:|---:|---:|")
for policy in ("drop-newest", "drop-oldest", "block"):
    d = load(f"overload_{policy}.json")
    for s in d["streams"]:
        if s["name"] == "_events":
            continue
        w(f"| {policy} | {s['name']} | {s['produced']} | {s['records']} | {s['ring_dropped_newest']} | "
          f"{s['ring_evicted_oldest']} | {s['producer_blocked_s']:.2f} |")
w("")
w("In every run produced = persisted + dropped + evicted for every stream, and the footer's per-stream "
  "`dropped` counter equals the ring's count.\n")

# ---------------------------------------------------------------- recovery
w("## Crash recovery time\n")
w("Command: `mr_record --unpaced --zstd-level 1 ...` killed with SIGKILL after 1 s / 4 s, then "
  "`mr_recover FILE.partial [--no-verify]`. \"cold\" = after `sync; echo 3 > /proc/sys/vm/drop_caches`.\n")
w("| .partial size | Mode | Cache | Chunks | Seconds | s per GB |")
w("|---:|---|---|---:|---:|---:|")
for label in ("256MB", "1GB"):
    d = load(f"recovery_{label}.json")
    for r in d["runs"]:
        gb = d["partial_bytes"] / 1e9
        w(f"| {d['partial_bytes'] / 1e6:,.0f} MB | {r['mode']} | {r['cache']} | {r['chunks']} | "
          f"{r['seconds']:.3f} | {r['seconds'] / gb:.2f} |")
w("")

# ---------------------------------------------------------------- replay
w("## Replay schedule accuracy\n")
w("Command: `mr_replay FILE --speed 1 [--spin-us 200]` on a 10 s recording at nominal rates; "
  "lateness = delivery time minus scheduled time.\n")
w("| Mode | Messages | p50 us | p90 us | p99 us | p99.9 us | max us |")
w("|---|---:|---:|---:|---:|---:|---:|")
for name, label in [("replay_1x_spin0.json", "sleep_until only"), ("replay_1x_spin200.json", "sleep + 200 us spin")]:
    d = load(name)
    l = d["lateness_us"]
    w(f"| {label} | {d['messages']} | {l['p50']:.1f} | {l['p90']:.1f} | {l['p99']:.1f} | {l['p999']:.1f} | {l['max']:.1f} |")
d = load("replay_max.json")
w(f"\nUnpaced replay (`--speed 0`): {d['messages']} messages, {d['bytes'] / 1e6:.1f} MB in "
  f"{d['elapsed_s']:.3f} s ({d['bytes'] / 1e6 / d['elapsed_s']:.0f} MB/s).\n")

(RES / "RESULTS.md").write_text("\n".join(out) + "\n")
print((RES / "RESULTS.md").read_text())
